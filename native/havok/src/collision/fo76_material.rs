const FO4_MATERIAL_DEFAULT: u32 = 0x064003D4;

pub fn is_supported_fo4_collision_material(crc: u32) -> bool {
    FO4_COLLISION_MATERIALS.contains(&crc)
}

pub fn remap_fo76_collision_material_for_fo4(crc: u32) -> u32 {
    if is_supported_fo4_collision_material(crc) {
        return crc;
    }
    FO76_ONLY_MATERIAL_MAP
        .iter()
        .find(|(source, _)| *source == crc)
        .map(|(_, target)| *target)
        .unwrap_or(FO4_MATERIAL_DEFAULT)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_explicit_mapping_targets_a_supported_non_stair_material() {
        for (source, target) in FO76_ONLY_MATERIAL_MAP {
            assert!(!is_supported_fo4_collision_material(source));
            assert!(is_supported_fo4_collision_material(target));
            assert_ne!(target, 0xC0EB623D);
            assert_eq!(remap_fo76_collision_material_for_fo4(source), target);
        }
    }

    #[test]
    fn fallback_is_supported_and_not_stairs() {
        assert!(is_supported_fo4_collision_material(FO4_MATERIAL_DEFAULT));
        assert_ne!(FO4_MATERIAL_DEFAULT, 0xC0EB623D);
        assert_eq!(
            remap_fo76_collision_material_for_fo4(0xDEAD_BEEF),
            FO4_MATERIAL_DEFAULT
        );
    }
}
